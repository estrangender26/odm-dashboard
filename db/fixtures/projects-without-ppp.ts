export const AUTHORITATIVE_PROJECTS_WITHOUT_PPP_EXPECTED_COUNT = 50;

/**
 * Programmatic assertion over the embedded authoritative dataset.
 *
 * Throws with the exact discrepancy when the dataset disagrees with the
 * invariants — it never silently adds or removes records.
 */
export function assertAuthoritativeProjectFixture(
  records: AuthoritativeProjectWithoutPPP[] = PROJECTS_WITHOUT_PPP_FIXTURE,
): { recordCount: number; uniqueTrackingIds: number } {
  const recordCount = records.length;
  const trackingIds = records.map((r) => r.trackingId);
  const uniqueTrackingIds = new Set(trackingIds).size;

  const problems: string[] = [];
  if (recordCount !== AUTHORITATIVE_PROJECTS_WITHOUT_PPP_EXPECTED_COUNT) {
    problems.push(
      `expected exactly ${AUTHORITATIVE_PROJECTS_WITHOUT_PPP_EXPECTED_COUNT} records but fixture contains ${recordCount}`,
    );
  }
  if (uniqueTrackingIds !== recordCount) {
    const duplicates = trackingIds.filter((id, index) => trackingIds.indexOf(id) !== index);
    problems.push(
      `expected ${recordCount} unique Tracking IDs but found ${uniqueTrackingIds}; duplicates: ${[...new Set(duplicates)].join(", ")}`,
    );
  }
  const excludedPresent = records.filter((r) =>
    (PPP_EXCLUDED_TRACKING_IDS as readonly string[]).includes(r.trackingId),
  );
  if (excludedPresent.length > 0) {
    problems.push(
      `PPP-excluded Tracking IDs must not be part of the Projects-without-PPP dataset but found: ${excludedPresent
        .map((r) => r.trackingId)
        .join(", ")}`,
    );
  }

  if (problems.length > 0) {
    throw new Error(`Authoritative Projects-without-PPP fixture invariant violation: ${problems.join("; ")}`);
  }

  return { recordCount, uniqueTrackingIds };
}
